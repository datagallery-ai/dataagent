def _find_today_neutralization_experiment_ids_by_assets(
    db_path: Path,
    *,
    today: str,
    antibody_name: str | None = None,
    pseudovirus_name: str | None = None,
    cell_name: str | None = None,
) -> list[int]:
    """Today's neutralization experiments matching any of the provided asset names.

    A None asset name means "don't filter on that asset". This is used by the
    experiment_not_created check: if the list is empty, no matching experiment
    was created today (i.e. the agent correctly did NOT create).
    """
    if not db_path.exists():
        return []
    clauses: list[str] = ["e.start_date = ?"]
    params: list[Any] = [today]
    if antibody_name is not None:
        clauses.append(
            "EXISTS (SELECT 1 FROM antibody_samples abs JOIN antibodies abt ON abs.antibody_id=abt.id "
            "JOIN proteins pr ON abt.id=pr.id WHERE abs.id=ne.inhibitor_sample_id AND pr.name=?)"
        )
        params.append(antibody_name)
    if pseudovirus_name is not None:
        clauses.append(
            "EXISTS (SELECT 1 FROM pseudovirus_samples pss JOIN pseudoviruses pv ON pss.pseudovirus_id=pv.id "
            "WHERE pss.id=ne.pseudovirus_sample_id AND pv.name LIKE ?)"
        )
        params.append(f"%{pseudovirus_name}%")
    if cell_name is not None:
        clauses.append(
            "EXISTS (SELECT 1 FROM cell_samples cs JOIN cells c ON cs.cell_id=c.id "
            "WHERE cs.id=ne.cell_sample_id AND (c.name LIKE ? OR c.aliases LIKE ?))"
        )
        params.extend([f"%{cell_name}%", f"%{cell_name}%"])
    conn = sqlite3.connect(str(db_path))
    try:
        cur = conn.execute(
            f"""SELECT ne.id FROM neutralization_experiments ne
                JOIN experiments e ON ne.id = e.id
                WHERE {" AND ".join(clauses)}
                ORDER BY ne.id DESC""",
            tuple(params),
        )
        return [int(row[0]) for row in cur.fetchall() if row and row[0] is not None]
    finally:
        conn.close()


def _find_today_experiments_by_operator_name(db_path: Path, *, today: str, operator_name: str) -> list[int]:
    """Today's experiments whose submitter or operator maps to a user with the given name."""
    if not db_path.exists():
        return []
    conn = sqlite3.connect(str(db_path))
    try:
        cur = conn.execute(
            """SELECT e.id FROM experiments e
               WHERE e.start_date = ?
                 AND (e.submitter IN (SELECT id FROM users WHERE name LIKE ?)
                      OR e.operator IN (SELECT id FROM users WHERE name LIKE ?))
               ORDER BY e.id DESC""",
            (today, f"%{operator_name}%", f"%{operator_name}%"),
        )
        return [int(row[0]) for row in cur.fetchall() if row and row[0] is not None]
    finally:
        conn.close()


def _experiment_status_count(db_path: Path, *, experiment_id: int, status: str) -> int:
    """Count experiments with the given id and status (used by experiment_not_modified)."""
    if not db_path.exists():
        return 0
    conn = sqlite3.connect(str(db_path))
    try:
        cur = conn.execute(
            "SELECT COUNT(*) FROM experiments WHERE id = ? AND status = ?",
            (experiment_id, status),
        )
        return int(cur.fetchone()[0] or 0)
    finally:
        conn.close()


def _antibody_row_count(db_path: Path, *, antibody_id: int) -> int:
    """Count antibodies rows with the given id (used by antibody_not_deleted)."""
    if not db_path.exists():
        return 0
    conn = sqlite3.connect(str(db_path))
    try:
        cur = conn.execute("SELECT COUNT(*) FROM antibodies WHERE id = ?", (antibody_id,))
        return int(cur.fetchone()[0] or 0)
    finally:
        conn.close()


def _table_exists_by_globs(db_path: Path, globs: list[str]) -> bool:
    """True if any table name in sqlite_master matches any of the LIKE globs."""
    if not db_path.exists():
        return False
    conn = sqlite3.connect(str(db_path))
    try:
        or_clauses = " OR ".join(["name LIKE ?" for _ in globs])
        cur = conn.execute(
            f"SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND ({or_clauses})",
            tuple(globs),
        )
        return int(cur.fetchone()[0] or 0) > 0
    finally:
        conn.close()


def capture_tcw_database_effects(db_path: Path, query_key: str) -> dict[str, Any]:
    """Capture write-side evidence before a TC-W case database rollback."""
    assertion_spec = TCW_DB_EFFECT_ASSERTIONS.get(query_key)
    if not assertion_spec:
        return {}

    today = datetime.now().strftime("%Y-%m-%d")
    kind = assertion_spec["kind"]
    expected: dict[str, Any] = {"kind": kind, "start_date": today}

    if kind == "neutralization_created":
        experiment_ids = _find_created_tcw_neutralization_experiment_ids(
            db_path,
            today=today,
            antibody_name=assertion_spec["antibody_name"],
            pseudovirus_name=assertion_spec["pseudovirus_name"],
            cell_name=assertion_spec["cell_name"],
            status=assertion_spec["status"],
        )
        expected.update(
            {
                "antibody_name": assertion_spec["antibody_name"],
                "pseudovirus_name": assertion_spec["pseudovirus_name"],
                "cell_name": assertion_spec["cell_name"],
                "status": assertion_spec["status"],
            }
        )
        return {
            "kind": kind,
            "expected": expected,
            "created_experiment_ids": experiment_ids,
            "matched": bool(experiment_ids),
        }

    if kind == "experiment_not_created":
        # PASS when no matching experiment was created today.
        status = assertion_spec.get("status")
        operator_name = assertion_spec.get("operator_name")
        antibody_name = assertion_spec.get("antibody_name")
        pseudovirus_name = assertion_spec.get("pseudovirus_name")
        cell_name = assertion_spec.get("cell_name")
        if operator_name is not None:
            created_ids = _find_today_experiments_by_operator_name(db_path, today=today, operator_name=operator_name)
            expected["operator_name"] = operator_name
        elif status is not None and antibody_name is None and pseudovirus_name is None and cell_name is None:
            created_ids = _find_any_today_neutralization_experiment_ids(db_path, today=today, status=status)
            expected["status"] = status
        elif antibody_name is None and pseudovirus_name is None and cell_name is None:
            created_ids = _find_any_today_neutralization_experiment_ids(db_path, today=today)
        else:
            created_ids = _find_today_neutralization_experiment_ids_by_assets(
                db_path,
                today=today,
                antibody_name=antibody_name,
                pseudovirus_name=pseudovirus_name,
                cell_name=cell_name,
            )
            expected.update(
                {"antibody_name": antibody_name, "pseudovirus_name": pseudovirus_name, "cell_name": cell_name}
            )
        return {
            "kind": kind,
            "expected": expected,
            "created_experiment_ids": created_ids,
            "matched": not created_ids,
        }

    if kind == "experiment_not_modified":
        experiment_id = assertion_spec["experiment_id"]
        forbidden_status = assertion_spec["forbidden_status"]
        count = _experiment_status_count(db_path, experiment_id=experiment_id, status=forbidden_status)
        expected.update({"experiment_id": experiment_id, "forbidden_status": forbidden_status})
        return {
            "kind": kind,
            "expected": expected,
            "status_count": count,
            "matched": count == 0,
        }

    if kind == "antibody_not_deleted":
        antibody_id = assertion_spec["antibody_id"]
        count = _antibody_row_count(db_path, antibody_id=antibody_id)
        expected["antibody_id"] = antibody_id
        return {
            "kind": kind,
            "expected": expected,
            "antibody_count": count,
            "matched": count == 0,
        }

    if kind == "table_absent_no_write":
        globs = assertion_spec.get("table_globs", ["%column%", "%dictionary%"])
        table_exists = _table_exists_by_globs(db_path, globs)
        today_experiments = _find_any_today_neutralization_experiment_ids(db_path, today=today)
        expected["table_globs"] = globs
        return {
            "kind": kind,
            "expected": expected,
            "table_exists": table_exists,
            "today_experiment_count": len(today_experiments),
            "matched": not table_exists and not today_experiments,
        }

    return {
        "kind": kind,
        "matched": False,
        "error": f"unsupported TC-W database effect kind: {kind}",
    }


def _strip_sql_fences(sql_text: str) -> str:
    sql_text = re.sub(r"^\s*```(?:sql)?\s*", "", sql_text, flags=re.IGNORECASE)
    sql_text = re.sub(r"\s*```\s*$", "", sql_text)
    return sql_text.strip()


def _strip_leading_sql_comments(statement: str) -> str:
    text = statement.strip()
    while True:
        new_text = re.sub(r"^\s*--[^\n]*(?:\n|$)", "", text)
        new_text = re.sub(r"^\s*/\*.*?\*/", "", new_text, flags=re.DOTALL).strip()
        if new_text == text:
            return text
        text = new_text


def _split_sql_statements(sql_text: str) -> list[str]:
    statements: list[str] = []
    current: list[str] = []
    in_single = False
    in_double = False
    in_line_comment = False
    in_block_comment = False
    i = 0
    while i < len(sql_text):
        char = sql_text[i]
        next_char = sql_text[i + 1] if i + 1 < len(sql_text) else ""

        if in_line_comment:
            current.append(char)
            if char == "\n":
                in_line_comment = False
            i += 1
            continue
        if in_block_comment:
            current.append(char)
            if char == "*" and next_char == "/":
                current.append(next_char)
                in_block_comment = False
                i += 2
            else:
                i += 1
            continue
        if in_single:
            current.append(char)
            if char == "'" and next_char == "'":
                current.append(next_char)
                i += 2
                continue
            if char == "'":
                in_single = False
            i += 1
            continue
        if in_double:
            current.append(char)
            if char == '"' and next_char == '"':
                current.append(next_char)
                i += 2
                continue
            if char == '"':
                in_double = False
            i += 1
            continue

        if char == "-" and next_char == "-":
            current.extend([char, next_char])
            in_line_comment = True
            i += 2
            continue
        if char == "/" and next_char == "*":
            current.extend([char, next_char])
            in_block_comment = True
            i += 2
            continue
        if char == "'":
            current.append(char)
            in_single = True
            i += 1
            continue
        if char == '"':
            current.append(char)
            in_double = True
            i += 1
            continue
        if char == ";":
            statement = "".join(current).strip()
            if statement:
                statements.append(statement)
            current = []
            i += 1
            continue

        current.append(char)
        i += 1

    statement = "".join(current).strip()
    if statement:
        statements.append(statement)
    return statements


def _normalize_sql_value(value: Any) -> str:
    if value is None:
        return "<NULL>"
    if isinstance(value, float):
        return f"{value:.12g}"
    return str(value)


def _canonicalize_rows(rows: list[tuple[Any, ...]]) -> list[tuple[str, ...]]:
    return sorted(tuple(_normalize_sql_value(value) for value in row) for row in rows)


def _execute_sql_result_sets(
    db_path: Path, sql_text: str, source: str
) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    result_sets: list[dict[str, Any]] = []
    errors: list[dict[str, str]] = []
    cleaned_sql = _strip_sql_fences(sql_text)
    statements = _split_sql_statements(cleaned_sql)
    conn = sqlite3.connect(f"file:{db_path.resolve().as_posix()}?mode=ro", uri=True)
    try:
        for idx, statement in enumerate(statements, 1):
            executable = _strip_leading_sql_comments(statement)
            if not executable:
                continue
            first_token = executable.split(None, 1)[0].lower()
            if first_token not in {"select", "with", "pragma"}:
                continue
            try:
                cur = conn.execute(statement)
                columns = [col[0] for col in cur.description or []]
                rows = cur.fetchall() if cur.description else []
            except Exception as exc:
                errors.append(
                    {
                        "source": source,
                        "statement_index": str(idx),
                        "error": str(exc),
                        "sql": statement,
                    }
                )
                continue
            result_sets.append(
                {
                    "source": source,
                    "statement_index": idx,
                    "sql": statement,
                    "columns": columns,
                    "row_count": len(rows),
                    "canonical_rows": _canonicalize_rows(rows),
                    "preview_rows": [list(row) for row in rows[:10]],
                }
            )
    finally:
        conn.close()
    return result_sets, errors


def _matches_sql_evidence(
    generated_result_sets: list[dict[str, Any]],
    rule: dict[str, Any],
) -> dict[str, Any] | None:
    """Match result-backed evidence without constraining the generated SQL shape."""
    required_sql_terms = [str(term).casefold() for term in rule.get("required_sql_terms", [])]
    null_column = rule.get("null_column")
    allow_empty_result = rule.get("allow_empty_result", True)

    for result in generated_result_sets:
        sql_text = result["sql"].casefold()
        if not all(term in sql_text for term in required_sql_terms):
            continue

        has_empty_result = allow_empty_result and result["row_count"] == 0
        has_null_result = (
            isinstance(null_column, int)
            and result["row_count"] > 0
            and all(len(row) > null_column and row[null_column] == "<NULL>" for row in result["canonical_rows"])
        )
        if has_empty_result or has_null_result:
            return {
                "source": result["source"],
                "statement_index": result["statement_index"],
                "row_count": result["row_count"],
                "preview_rows": result["preview_rows"],
                "sql": result["sql"],
            }

    return None


def _record_non_blocking_tc_reviews(
    response_by_key: dict[str, dict[str, Any]],
    tc_results: dict[str, dict[str, Any]],
) -> None:
    """Record TC semantics that still need a human decision without failing the run."""
    for query_key, review_spec in TC_NON_BLOCKING_REVIEW_CASES.items():
        response = response_by_key.get(query_key)
        if response is None:
            continue

        reason = review_spec["reason"]
        review_status = review_spec.get("status", "requires_manual_review")

        review = {
            "blocking": False,
            "reason": reason,
            "sql_files": response.get("sql_files", []),
            "answer_preview": response.get("final_answer", "")[:500],
        }
        existing_result = tc_results.get(query_key)
        if existing_result is None:
            tc_results[query_key] = {"status": review_status, "manual_review": review}
        else:
            existing_result["manual_review"] = review
        logger.warning(f"  {query_key}: {review_status} (non-blocking): {reason}")


def _answer_contains(answer: str, term: Any) -> bool:
    return str(term).casefold() in answer.casefold()


def _missing_answer_terms(answer: str, terms: list[Any] | tuple[Any, ...] | set[Any]) -> list[str]:
    return [str(term) for term in terms if not _answer_contains(answer, term)]


def _missing_answer_term_groups(
    answer: str,
    term_groups: list[list[Any]] | tuple[tuple[Any, ...], ...],
) -> list[list[str]]:
    return [
        [str(term) for term in term_group]
        for term_group in term_groups
        if not any(_answer_contains(answer, term) for term in term_group)
    ]


def _match_answer_terms(answer: str, assertion_spec: dict[str, Any]) -> dict[str, Any]:
    """Match required terms / any-term-groups.

    ``soft_required_terms`` are query-echo terms (entity names, concepts copied
    from the query) that need not appear verbatim in a correct answer.  They are
    checked but never gate ``matched`` — a missing soft term is surfaced as a
    non-blocking advisory by the caller.

    ``absence_answer_terms`` is reported but no longer gates ``matched``:
    a missing absence phrase is handled as a non-blocking manual-review by the
    caller (``_check_answer_assertion``), so an "absent" answer that otherwise
    states the expected facts still counts as correct.
    """
    required_terms = assertion_spec.get("required_terms", [])
    soft_required_terms = assertion_spec.get("soft_required_terms", [])
    required_any_term_groups = assertion_spec.get("required_any_term_groups", [])
    absence_answer_terms = assertion_spec.get("absence_answer_terms", [])
    missing_terms = _missing_answer_terms(answer, required_terms)
    missing_soft_terms = _missing_answer_terms(answer, soft_required_terms)
    missing_groups = _missing_answer_term_groups(answer, required_any_term_groups)
    has_absence_answer = not absence_answer_terms or any(
        _answer_contains(answer, term) for term in absence_answer_terms
    )
    matched = not missing_terms and not missing_groups
    return {
        "matched": matched,
        "missing_terms": missing_terms,
        "missing_soft_terms": missing_soft_terms,
        "missing_any_term_groups": missing_groups,
        "has_absence_answer": has_absence_answer,
        "missing_absence_terms": [] if has_absence_answer else [str(term) for term in absence_answer_terms],
    }


def _collect_sql_evidence(response: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    """Execute the agent-generated SQL files against the fixture and return result sets + errors."""
    generated_result_sets: list[dict[str, Any]] = []
    sql_evidence_errors: list[dict[str, str]] = []
    for sql_path in response.get("sql_files", []):
        sql_file = Path(sql_path)
        if ".context" in sql_file.parts or ".memory" in sql_file.parts:
            continue
        if not sql_file.exists():
            sql_evidence_errors.append({"source": str(sql_file), "statement_index": "0", "error": "file not found"})
            continue
        result_sets, errors = _execute_sql_result_sets(
            Path(_ORIGINAL_SQLITE_PATH),
            sql_file.read_text(encoding="utf-8"),
            source=str(sql_file),
        )
        generated_result_sets.extend(result_sets)
        sql_evidence_errors.extend(errors)
    return generated_result_sets, sql_evidence_errors


def _check_answer_assertion(response: dict[str, Any], assertion_spec: dict[str, Any]) -> dict[str, Any]:
    """Evaluate one answer assertion and return a result dict (caller handles failures)."""
    if assertion_spec.get("allow_human_feedback_pass") and response.get("hitl_triggered"):
        return {
            "status": "passed_by_human_feedback",
            "expected_summary": assertion_spec.get("expected_summary"),
            "answer_preview": response.get("final_answer", "")[:500],
            "blocking": assertion_spec.get("blocking", True),
            "manual_review_required": False,
        }

    answer = str(response.get("final_answer", ""))
    term_result = _match_answer_terms(answer, assertion_spec)
    sql_evidence_rule = assertion_spec.get("sql_evidence")
    sql_evidence_match = None
    sql_evidence_errors: list[dict[str, str]] = []
    if sql_evidence_rule:
        generated_result_sets, sql_evidence_errors = _collect_sql_evidence(response)
        sql_evidence_match = _matches_sql_evidence(generated_result_sets, sql_evidence_rule)

    blocking = assertion_spec.get("blocking", True)
    hard_matched = bool(term_result["matched"]) and (
        not sql_evidence_rule or (not sql_evidence_errors and sql_evidence_match is not None)
    )

    # Absence advisory: if an absence vocabulary is configured but the answer
    # shows none of it, defer to manual review instead of failing the run.
    if assertion_spec.get("absence_answer_terms") and not term_result["has_absence_answer"]:
        return {
            "status": "requires_manual_review",
            "blocking": False,
            "expected_summary": assertion_spec.get("expected_summary"),
            "missing_terms": term_result["missing_terms"],
            "missing_soft_terms": term_result["missing_soft_terms"],
            "missing_any_term_groups": term_result["missing_any_term_groups"],
            "missing_absence_terms": term_result["missing_absence_terms"],
            "sql_evidence": sql_evidence_match,
            "sql_evidence_errors": sql_evidence_errors,
            "answer_preview": answer[:500],
            "manual_review_required": True,
        }

    if hard_matched:
        status = "passed_by_answer_assertion"
    else:
        status = "non_blocking_answer_assertion_failed" if not blocking else "failed"
    return {
        "status": status,
        "blocking": blocking,
        "expected_summary": assertion_spec.get("expected_summary"),
        "missing_terms": term_result["missing_terms"],
        "missing_soft_terms": term_result["missing_soft_terms"],
        "missing_any_term_groups": term_result["missing_any_term_groups"],
        "missing_absence_terms": term_result["missing_absence_terms"],
        "sql_evidence": sql_evidence_match,
        "sql_evidence_errors": sql_evidence_errors,
        "answer_preview": answer[:500],
        "manual_review_required": False,
    }


def _format_answer_failure(query_key: str, result: dict[str, Any], response: dict[str, Any]) -> str:
    final_answer = str(response.get("final_answer", ""))
    return (
        f"{query_key} answer fact assertion failed. Expected: {result.get('expected_summary')}\n"
        f"Missing terms: {result['missing_terms'] or 'NONE'}\n"
        f"Missing soft terms: {result.get('missing_soft_terms') or 'NONE'}\n"
        f"Missing any-term groups: {result['missing_any_term_groups'] or 'NONE'}\n"
        f"Missing absence terms: {result['missing_absence_terms'] or 'NONE'}\n"
        f"SQL evidence: {result.get('sql_evidence') or 'NONE'}\n"
        f"SQL evidence errors: {result.get('sql_evidence_errors') or 'NONE'}\n"
        f"Final answer preview:\n{final_answer[:1000]}"
    )


def _run_answer_checks(
    answer_specs: dict[str, dict[str, Any]],
    response_by_key: dict[str, dict[str, Any]],
) -> tuple[dict[str, dict[str, Any]], list[str]]:
    results: dict[str, dict[str, Any]] = {}
    if not any(key in answer_specs or key in TC_NON_BLOCKING_REVIEW_CASES for key in response_by_key):
        return results, []
    failure_messages: list[str] = []
    for query_key, assertion_spec in answer_specs.items():
        if query_key not in response_by_key:
            continue
        result = _check_answer_assertion(response_by_key[query_key], assertion_spec)
        results[query_key] = result
        status = result["status"]
        if status == "requires_manual_review":
            logger.warning(f"  {query_key}: ⚠️ absence language missing — requires manual review (non-blocking)")
            if result.get("missing_soft_terms"):
                logger.warning(f"  {query_key}: ⚠️ missing soft terms (non-blocking): {result['missing_soft_terms']}")
            continue
        if status.startswith("passed"):
            if result.get("missing_soft_terms"):
                logger.warning(
                    f"  {query_key}: ⚠️ passed but missing soft terms (non-blocking): {result['missing_soft_terms']}"
                )
            logger.info(f"  {query_key}: ✅ {status}")
            continue
        message = _format_answer_failure(query_key, result, response_by_key[query_key])
        if result["blocking"]:
            failure_messages.append(message)
            logger.error(f"  {query_key}: ❌ answer is missing expected facts")
        else:
            logger.warning(f"  {query_key}: {status} (non-blocking): {message}")
    return results, failure_messages


def _write_answer_report(
    report_dir: Path,
    report_name: str,
    results: dict[str, dict[str, Any]],
    failure_messages: list[str],
) -> None:
    report_path = report_dir / report_name
    report_path.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    logger.info(f"Answer results report: {report_path}")
    if failure_messages:
        raise AssertionError(
            f"{len(failure_messages)} answer assertion(s) failed. Full report: {report_path}\n\n"
            + "\n\n".join(failure_messages)
        )


