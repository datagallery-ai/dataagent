    # ---- Q4: count_cells -----------------------------------------------
    if "count_cells" in response_by_key:
        q4_answer = response_by_key["count_cells"].get("final_answer", "")
        missing_ids = [cid for cid in EXPECTED_CELL_IDS if cid not in q4_answer]
