#!/usr/bin/env python3
"""Render ``step2_0_profile_report.md`` from the step2_0 profile dump.

Deterministic parts (headers, per-table overview, 7-column table, list-field
summary) are generated by this script so the Agent never hand-writes them.

Only one thing needs semantic reasoning: whether a field whose ``n_unique > 1`` is
really a *semantic constant* (multiple distinct values that all mean "no info",
e.g. ``未知`` / ``none`` / ``-`` / ``其他``). Those rows are emitted as
``constant:TODO`` and also listed in ``step2_0_semantic_todo.json``; the Agent edits the
markdown in place, replacing ``constant:TODO`` with ``constant:semantic`` or
``constant:false``. Everything else is hard-computed:

  * ``constant:true``  -> ``n_unique <= 1``
  * ``delimiter:"#"`` / ``"^"`` / ``null`` -> from ``sample_values``
  * ``constant:false`` -> normal multi-value field without a delimiter
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

PROTECTED_SUFFIX = "（保护列）"
TABLE_HEADER = "| 特征名 | 数据类型 | 空值率 | 唯一值 | 特征含义 | 样例值 | 分布分析 |"
TABLE_SEP = "|--------|---------|--------|--------|---------|--------|---------|"
LIST_HEADER = "## 列表字段检测结果"
LIST_TABLE_HEADER = "| 字段名 | 所在表 | list_delimiter |"
LIST_TABLE_SEP = "|--------|--------|---------------|"

_ROW_RE = re.compile(
    r"^\|\s*(?P<field>[^|]+?)\s*\|\s*(?P<type>[^|]*?)\s*\|\s*(?P<null>[^|]*?)\s*\|\s*(?P<uniq>[^|]*?)\s*\|"
    r"\s*(?P<meaning>[^|]*?)\s*\|\s*(?P<samples>[^|]*?)\s*\|\s*constant:(?P<constant>[^,]+),\s*delimiter:(?P<delim>[^|]+?)\s*\|"
)


def _read_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"无法读取 {path}：{exc}") from exc
    if not isinstance(value, dict):
        raise SystemExit(f"{path} 必须包含一个 JSON 对象")
    return value


def _format_rate(value: Any) -> str:
    try:
        rate = float(value)
    except (TypeError, ValueError):
        return "0%"
    return f"{rate:g}%"


def _format_unique(n_unique: Any, sample_values: str) -> str:
    if n_unique is None:
        return "TODO"
    count = int(n_unique)
    text = str(count)
    if count <= 10 and sample_values.strip():
        values = [part.strip() for part in sample_values.split(",") if part.strip()]
        if values:
            text = f"{count}（{', '.join(values)}）"
    return text


def _delimiter_of(sample_values: str) -> str:
    text = str(sample_values or "")
    if "#" in text:
        return '"#"'
    if "^" in text:
        return '"^"'
    return "null"


def _no_info_keywords() -> tuple[str, ...]:
    return ("未知", "无", "其他", "其它", "暂无", "空", "none", "null", "nan", "unknown", "-", "n/a")


def _is_semantic_candidate(record: dict[str, Any], max_unique: int) -> bool:
    n_unique = record.get("n_unique")
    if not isinstance(n_unique, int) or n_unique <= 1 or n_unique > max_unique:
        return False
    data_type = str(record.get("data_type") or "")
    if "String" not in data_type:
        return False
    if _delimiter_of(record.get("sample_values")) != "null":
        return False
    samples = [part.strip().lower() for part in str(record.get("sample_values") or "").split(",") if part.strip()]
    return any(any(key in value for key in _no_info_keywords()) for value in samples)


def _distribution(record: dict[str, Any], is_protected: bool, max_unique: int) -> tuple[str, bool]:
    """Return ``(distribution_cell, needs_agent)``."""
    delimiter = _delimiter_of(record.get("sample_values"))
    n_unique = record.get("n_unique")
    if delimiter != "null":
        return f'constant:false, delimiter:{delimiter}', False
    if isinstance(n_unique, int) and n_unique <= 1:
        return "constant:true, delimiter:null", False
    if not is_protected and _is_semantic_candidate(record, max_unique):
        return "constant:TODO, delimiter:null", True
    return "constant:false, delimiter:null", False


def _granularity(classification: str) -> str:
    return {
        "1:1用户表": "1行=1用户",
        "1:N行为表": "1行=1行为记录",
        "维度表": "1行=1实体",
    }.get(classification, "TODO")


def _table_map(meta: dict[str, Any]) -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    for table in meta.get("tables") or []:
        if isinstance(table, dict) and table.get("name"):
            result[str(table["name"]).strip()] = table
    return result


def _column_descriptions(meta: dict[str, Any]) -> dict[tuple[str, str], str]:
    result: dict[tuple[str, str], str] = {}
    for table in meta.get("tables") or []:
        if not isinstance(table, dict) or not table.get("name"):
            continue
        table_name = str(table["name"]).strip()
        for column in table.get("columns") or []:
            if not isinstance(column, dict) or not column.get("name"):
                continue
            description = str(column.get("description") or "").strip()
            result[(table_name, str(column["name"]).strip())] = description
    return result


def render(
    dump: dict[str, Any],
    meta: dict[str, Any],
    schema: dict[str, Any],
    max_unique: int,
) -> tuple[str, list[dict[str, Any]], list[str]]:
    table_profile = {
        str(row.get("table_name") or "").strip(): row
        for row in (dump.get("table_profile") or [])
        if isinstance(row, dict) and row.get("table_name")
    }
    columns_by_table: dict[str, list[dict[str, Any]]] = {}
    for row in dump.get("column_profile") or []:
        if not isinstance(row, dict):
            continue
        table_name = str(row.get("table_name") or "").strip()
        if table_name:
            columns_by_table.setdefault(table_name, []).append(row)

    table_meta = _table_map(meta)
    descriptions = _column_descriptions(meta)
    protected = {
        str(schema.get("user_id") or "").strip(),
        str(schema.get("label") or "").strip(),
        str(schema.get("age") or "").strip(),
        str(schema.get("gender") or "").strip(),
    } - {""}

    ordered_tables = [str(item.get("table_name") or "").strip() for item in schema.get("source_tables") or []]
    if not ordered_tables:
        ordered_tables = sorted(columns_by_table)

    lines: list[str] = ["# 源数据分析", ""]
    semantic_todo: list[dict[str, Any]] = []
    list_rows: list[tuple[str, str, str]] = []

    for table_name in ordered_tables:
        profile = table_profile.get(table_name, {})
        classification = str(profile.get("classification") or "TODO").strip()
        columns = columns_by_table.get(table_name, [])
        table_desc = str((table_meta.get(table_name) or {}).get("description") or "").strip() or "TODO"
        key_column = ""
        for item in schema.get("source_tables") or []:
            if str(item.get("table_name") or "").strip() == table_name:
                key_column = str(item.get("user_key") or "").strip()
                break
        key_column = key_column or str(schema.get("user_id") or "").strip() or "—"

        lines.append(f"### {table_name}（{len(columns)} 列）")
        lines.append("")
        lines.append(
            f"**表名**：{table_name}，**业务含义**：{table_desc}，**粒度**：{_granularity(classification)}，"
            f"**主键**：{key_column}，**行数**：{profile.get('total_rows', 'TODO')}，"
            f"**用户数**：{profile.get('unique_user_id', 'TODO')}，**分类**：{classification}"
        )
        lines.append("")
        lines.append(TABLE_HEADER)
        lines.append(TABLE_SEP)

        for record in sorted(columns, key=lambda item: str(item.get("column_name") or "")):
            field = str(record.get("column_name") or "").strip()
            data_type = str(record.get("data_type") or "Unknown").strip()
            is_protected = field in protected
            distribution, needs_agent = _distribution(record, is_protected, max_unique)
            if needs_agent:
                semantic_todo.append(
                    {
                        "table": table_name,
                        "field": field,
                        "data_type": data_type,
                        "n_unique": record.get("n_unique"),
                        "sample_values": record.get("sample_values"),
                    }
                )
            meaning = descriptions.get((table_name, field), "") or "-"
            samples = str(record.get("sample_values") or "").strip() or "（空）"
            lines.append(
                f"| {field} | {data_type} | {_format_rate(record.get('missing_rate'))} | "
                f"{_format_unique(record.get('n_unique'), samples)} | {meaning} | {samples} | {distribution} |"
            )
            if (
                "String" in data_type
                and isinstance(record.get("n_unique"), int)
                and record["n_unique"] > 5
            ) or _delimiter_of(record.get("sample_values")) != "null":
                list_rows.append((field, table_name, _delimiter_of(record.get("sample_values"))))

        lines.append("")

    lines.append(LIST_HEADER)
    lines.append("")
    lines.append(LIST_TABLE_HEADER)
    lines.append(LIST_TABLE_SEP)
    for field, table_name, delimiter in sorted(list_rows):
        lines.append(f"| {field} | {table_name} | {delimiter} |")
    lines.append("")

    list_fields = sorted(
        {field for field, _table, delimiter in list_rows if delimiter in {'"#"', '"^"'}}
    )
    return "\n".join(lines), semantic_todo, list_fields


def main() -> None:
    parser = argparse.ArgumentParser(description="Render step2_0_profile_report.md")
    parser.add_argument("--dump", type=Path, required=True, help="step2_0_profile_dump.json")
    parser.add_argument("--meta", type=Path, required=True, help="step1_output_meta.json")
    parser.add_argument("--schema", type=Path, required=True, help="schema_resolution.json")
    parser.add_argument("--out", type=Path, default=Path("step2_0_profile_report.md"))
    parser.add_argument("--semantic-todo", type=Path, default=Path("step2_0_semantic_todo.json"))
    parser.add_argument(
        "--list-fields",
        type=Path,
        default=Path("list_fields.txt"),
        help="authoritative list-field name file consumed by step2_2 (one field per line)",
    )
    parser.add_argument(
        "--semantic-candidate-max-unique",
        type=int,
        default=10,
        help="String fields with n_unique <= this are semantic-constant candidates",
    )
    args = parser.parse_args()

    dump = _read_json(args.dump)
    meta = _read_json(args.meta)
    schema = _read_json(args.schema)

    markdown, semantic_todo, list_fields = render(dump, meta, schema, args.semantic_candidate_max_unique)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(markdown.rstrip() + "\n", encoding="utf-8")
    args.semantic_todo.write_text(
        json.dumps({"candidates": semantic_todo}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    args.list_fields.write_text(
        "".join(f"{field}\n" for field in list_fields),
        encoding="utf-8",
    )

    print(f"已写出 {args.out}")
    print(f"已写出 {args.semantic_todo}：{len(semantic_todo)} 行 constant:TODO 待你判定")
    print(f"已写出 {args.list_fields}：{len(list_fields)} 个列表字段")
    if not semantic_todo:
        print("无语义常量候选，md 中不含 constant:TODO 行")


if __name__ == "__main__":
    main()
